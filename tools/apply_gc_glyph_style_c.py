#!/usr/bin/env python3
"""tools/apply_gc_glyph_style_c.py -- put the approved GameCube glyphs
(style C "Shallow relief", 12px fixes; maintainer-approved 2026-10-06,
tmp/jobs/gc-glyphs-1006/DECISION.md) into atlas cells 32-41.

Both atlases carry the GameCube cells: gui_util.c's gutil_glyph_texture()
draws cells < 42 from gui/approved-controls.png and falls back to
controls.png when that texture is not loaded, so the two must agree.

Each 32x32 cell is REPLACED (not alpha-composited) by the CC0 artwork in
artwork/controller-glyphs/gamecube-style-c/. Every other decoded pixel of
each atlas is verified unchanged. Idempotent: a second run is a no-op.

assets/controls.png is generated by tools/gen_cc0_controls.py, which pastes
the same cells through paste_style_c() below, so regenerating it keeps them.

    python3 tools/apply_gc_glyph_style_c.py [--check]
"""
import argparse
import hashlib
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "artwork" / "controller-glyphs" / "gamecube-style-c"
CELL = 32
COLS = 8
ATLASES = ("assets/gui/approved-controls.png", "assets/controls.png")

# Cell -> (file, sha256 of the PNG file). Hashes are those recorded for
# variant C in tmp/jobs/gc-glyphs-1006/glyph-manifest.json.
STYLE_C = {
    32: ("32-A.png", "4f36a0867bee3328"),
    33: ("33-B.png", "bef227d6035089e5"),
    34: ("34-X.png", "1e8ac0f25a3227bf"),
    35: ("35-Y.png", "aa0564f7a462d6ce"),
    36: ("36-Z.png", "97b6073d354cd4e2"),
    37: ("37-L.png", "780da5304c006446"),
    38: ("38-R.png", "32b1666e761f195b"),
    39: ("39-Start.png", "d6073e99c5be5a5e"),
    40: ("40-control-stick.png", "d55f4a307014d3bb"),
    41: ("41-C-stick.png", "5652b8d132f00c93"),
}


def cell_box(cell):
    x, y = (cell % COLS) * CELL, (cell // COLS) * CELL
    return (x, y, x + CELL, y + CELL)


def load_style_c():
    cells = {}
    for cell, (name, digest) in STYLE_C.items():
        path = ART / name
        got = hashlib.sha256(path.read_bytes()).hexdigest()
        if not got.startswith(digest):
            raise SystemExit(f"{path}: sha256 {got[:16]} != manifest {digest}")
        img = Image.open(path).convert("RGBA")
        if img.size != (CELL, CELL):
            raise SystemExit(f"{path}: {img.size}, expected 32x32")
        cells[cell] = img
    return cells


def paste_style_c(atlas):
    """Replace cells 32-41 of an RGBA atlas in place; returns the atlas."""
    for cell, img in load_style_c().items():
        atlas.paste(img, cell_box(cell))
    return atlas


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify only; exit 1 if an atlas needs updating")
    args = ap.parse_args()
    cells = load_style_c()
    stale = []
    for rel in ATLASES:
        path = ROOT / rel
        before = Image.open(path).convert("RGBA")
        if before.size != (256, 256):
            raise SystemExit(f"{rel}: {before.size}, expected 256x256")
        after = before.copy()
        for cell, img in cells.items():
            after.paste(img, cell_box(cell))
        # Outside cells 32-41 nothing may move.
        mask_before, mask_after = before.copy(), after.copy()
        for cell in cells:
            blank = Image.new("RGBA", (CELL, CELL))
            mask_before.paste(blank, cell_box(cell))
            mask_after.paste(blank, cell_box(cell))
        assert mask_before.tobytes() == mask_after.tobytes()
        if before.tobytes() == after.tobytes():
            print(f"[gc-style-c] {rel}: already style C")
            continue
        stale.append(rel)
        if not args.check:
            after.save(path)
            print(f"[gc-style-c] {rel}: cells 32-41 replaced")
    if args.check and stale:
        print(f"[gc-style-c] stale: {', '.join(stale)}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
