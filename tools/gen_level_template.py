#!/usr/bin/env python3
"""
Generate source/network/level_template.h: a minimal, valid Beta 1.7.3 level.dat
(gzip NBT) embedded as a C byte array. The new-world flow parses this template,
overwrites the dynamic fields (RandomSeed, SpawnXYZ, Player.Pos, ...) and saves
it -- reusing the proven level_archive parse/write/save path instead of building
the cNBT tree by hand.

Run from the repo root:  python tools/gen_level_template.py
"""
import gzip
import struct
import os

def tag(tid, name, payload):
    return bytes([tid]) + struct.pack(">H", len(name)) + name.encode("utf-8") + payload

def t_byte(n, v):   return tag(1, n, struct.pack(">b", v))
def t_short(n, v):  return tag(2, n, struct.pack(">h", v))
def t_int(n, v):    return tag(3, n, struct.pack(">i", v))
def t_long(n, v):   return tag(4, n, struct.pack(">q", v))
def t_float(n, v):  return tag(5, n, struct.pack(">f", v))
def t_double(n, v): return tag(6, n, struct.pack(">d", v))
def t_string(n, s): return tag(8, n, struct.pack(">H", len(s)) + s.encode("utf-8"))
def t_compound(n, *children): return tag(10, n, b"".join(children) + b"\x00")
def t_list_double(n, vals):
    return tag(9, n, bytes([6]) + struct.pack(">i", len(vals))
               + b"".join(struct.pack(">d", v) for v in vals))
def t_list_float(n, vals):
    return tag(9, n, bytes([5]) + struct.pack(">i", len(vals))
               + b"".join(struct.pack(">f", v) for v in vals))
def t_list_empty_compound(n):
    return tag(9, n, bytes([10]) + struct.pack(">i", 0))

# Default player: full CaveWii health (10 hearts * 16 engine hp), empty
# inventory, looking level, at a placeholder spawn. The create flow explicitly
# overwrites Health too, keeping this generated fallback and runtime policy in
# lockstep without changing ambiguous legacy/imported-save values.
player = t_compound(
    "Player",
    t_short("Health", 160),
    t_short("AttackTime", 0),
    t_short("HurtTime", 0),
    t_short("DeathTime", 0),
    t_short("Air", 300),
    t_short("Fire", -20),
    t_float("FallDistance", 0.0),
    t_int("Dimension", 0),
    t_byte("OnGround", 1),
    t_list_double("Pos", [0.5, 64.0, 0.5]),
    t_list_float("Rotation", [0.0, 0.0]),
    t_list_double("Motion", [0.0, 0.0, 0.0]),
    t_list_empty_compound("Inventory"),
)

data = t_compound(
    "Data",
    t_long("RandomSeed", 0),
    t_long("Time", 0),
    t_long("LastPlayed", 0),
    t_long("SizeOnDisk", 0),
    t_int("SpawnX", 0),
    t_int("SpawnY", 64),
    t_int("SpawnZ", 0),
    t_byte("thundering", 0),
    t_byte("raining", 0),
    t_int("rainTime", 0),
    t_int("thunderTime", 0),
    t_int("version", 19132),
    # CaveWii generator pin (2026-06-11 feasibility blocker P-1): which terrain
    # generator owns this world, FOREVER. 1 = byte-faithful Beta 1.7.3. A future
    # Release-1.0 generator gets its own value; chunks are NEVER generated by a
    # different generator than the world was created with (no Mojang-style 1.8
    # frontier seams). ABSENT tag == 1 by definition: tag-less worlds (imported
    # real Beta saves, pre-tag CaveWii saves) predate any second generator.
    # Real Minecraft ignores unknown tags, so imported-back worlds stay valid.
    t_int("CaveWiiGenerator", 1),
    # CaveWii persistence schema. Missing means legacy version 0; new worlds
    # start at the current version. Unknown tags remain harmless to Beta itself.
    # Version 4 (FH-17): dungeon mob spawners persist a faithful MobSpawner
    # tile entity instead of a metadata-encoded mob type; a brand-new world
    # never has any legacy-encoded spawner to migrate, so it starts here
    # directly.
    t_int("CaveWiiSaveVersion", 4),
    t_string("LevelName", "New World"),
    player,
)

root = t_compound("", data)
blob = gzip.compress(root, mtime=0)

out = os.path.join("source", "network", "level_template.h")
with open(out, "w", newline="\n") as f:
    f.write("// AUTO-GENERATED by tools/gen_level_template.py -- do not edit.\n")
    f.write("// A minimal valid Beta 1.7.3 level.dat (gzip NBT); the new-world\n")
    f.write("// flow parses it, overwrites RandomSeed/SpawnXYZ/Player.Pos, saves.\n")
    f.write("#ifndef LEVEL_TEMPLATE_H\n#define LEVEL_TEMPLATE_H\n\n")
    f.write("static const unsigned char LEVEL_DAT_TEMPLATE[] = {\n")
    for i in range(0, len(blob), 12):
        f.write("\t" + ", ".join("0x%02x" % b for b in blob[i:i+12]) + ",\n")
    f.write("};\n\n#endif\n")

print("wrote %s (%d bytes gzip, %d raw NBT)" % (out, len(blob), len(root)))
