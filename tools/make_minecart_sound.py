#!/usr/bin/env python3
"""
Generate the (RETIRED-FROM-SHIPPING) minecart rolling sound placeholder — an
ORIGINAL, synthesized asset.

STATUS (2026-09-03): this generator's output is NO LONGER part of the shipped
default pack. assets/sound/minecart/base{1,2,3}.wav were removed from the
repo the same day: the maintainer asked for "the proper sound", and the
proper sound is the real modern Mojang minecraft/sounds/minecart/{base,inside}
.ogg pair, imported from the user's OWN owned modern Minecraft install via
`tools/import_owned_beta_assets.py --modern-minecraft <dir>` (never shipped in
this repo — same never-commit-Mojang-audio rule as the Beta asset importer).
Until a user runs that import, SOUND_MINECART_BASE/SOUND_MINECART_INSIDE now
ship NO bundled default at all, so a stock pack's carts are genuinely silent,
matching Beta 1.7.3 (see audio_sound_table.h). This script is kept only so the
synthesized placeholder can still be regenerated by hand if a future
maintainer decision wants it back; it is not invoked by any build or import
step any more.

WHY IT EXISTED. Beta 1.7.3 ships no minecart sound: EntityMinecart has no
playSound call and no "minecart.*" key exists anywhere in the 740c583
decompile (those arrived around 1.5 as unused assets, and are not part of the
real b1.7.3 jar/resources tree even in the decompile pack's own sidecar
folders — see audio_sound_table.h's SOUND_MINECART_BASE comment). So a
faithful Beta cart is silent, and there was no authentic 1.7.3 asset to
import even from a user-owned Beta jar.

The maintainer asked for a sound anyway on 2026-08-04, as an explicit,
documented deviation. That left provenance as the real constraint: shipping a
later Mojang minecart sample would put non-free IP in the tree, which this
project deliberately avoids. So the sample was SYNTHESIZED here from first
principles — no recorded source, no third-party audio — which makes it
unambiguously the project's own work, redistributable under the repo's own
licence. Same reasoning, and the same offline-generator shape, as the
procedural lava/flame texture FX. Clean provenance was never the problem this
retirement solves — "not the proper (real) sound" was.

WHAT IT SOUNDS LIKE. One short "cart passes over a rail joint" event, meant to
be RETRIGGERED on the cart's distance odometer rather than looped (the engine
mixer is 16 one-shot voices with no loop support):
  * a low body rumble  — the cart shell resonating, two detuned sines
  * a mid rattle       — band-passed noise, the loose metal
  * a joint transient  — a short click at onset, the wheel crossing the gap
Three variants are emitted so repeated playback does not machine-gun; the
engine would pick among base1..base3 automatically (audio_registry variant
scan) IF they were present under assets/ -- they no longer are.

Usage (manual regeneration only):
  python tools/make_minecart_sound.py [--dest assets/sound/minecart]
"""

import argparse
import math
import os
import random
import struct

RATE = 22050  # matches the rest of the pack; plenty for a low rumble
DUR = 0.26  # seconds — short, so retriggering stays crisp


def _synth(seed):
    """One rail-joint event. Returns a list of floats in [-1, 1]."""
    rng = random.Random(seed)
    n = int(RATE * DUR)
    out = [0.0] * n

    # Slight per-variant detune so the three do not sound like one sample.
    body_hz = 62.0 * (1.0 + rng.uniform(-0.06, 0.06))
    body2_hz = body_hz * 1.5
    rattle_hz = 900.0 * (1.0 + rng.uniform(-0.15, 0.15))

    # One-pole state for the band-passed noise.
    lp = 0.0
    hp_prev = 0.0
    lp_a = 1.0 - math.exp(-2.0 * math.pi * rattle_hz / RATE)

    for i in range(n):
        t = i / RATE
        # Envelopes: fast attack, exponential decay. The transient is much
        # shorter than the body so the click reads as a separate event.
        env_body = math.exp(-t * 11.0)
        env_rattle = math.exp(-t * 26.0)
        env_click = math.exp(-t * 190.0)

        body = math.sin(2.0 * math.pi * body_hz * t) * 0.55
        body += math.sin(2.0 * math.pi * body2_hz * t) * 0.22

        white = rng.uniform(-1.0, 1.0)
        lp += lp_a * (white - lp)  # low-pass
        band = lp - hp_prev  # crude high-pass of the LP => band-pass
        hp_prev += 0.0025 * (lp - hp_prev)

        click = rng.uniform(-1.0, 1.0) * env_click * 0.5

        s = body * env_body + band * env_rattle * 0.8 + click
        out[i] = s

    # Normalise to a consistent peak, then leave headroom: the engine scales by
    # speed at play time and several carts may overlap on the 16-voice mixer.
    peak = max(1e-9, max(abs(v) for v in out))
    gain = 0.72 / peak
    for i in range(n):
        out[i] *= gain

    # De-click the very start/end so retriggering never pops.
    fade = int(RATE * 0.004)
    for i in range(fade):
        w = i / fade
        out[i] *= w
        out[n - 1 - i] *= w
    return out


def _write_wav(path, samples):
    frames = b"".join(
        struct.pack("<h", max(-32768, min(32767, int(v * 32767.0)))) for v in samples
    )
    with open(path, "wb") as f:
        f.write(b"RIFF")
        f.write(struct.pack("<I", 36 + len(frames)))
        f.write(b"WAVEfmt ")
        f.write(struct.pack("<IHHIIHH", 16, 1, 1, RATE, RATE * 2, 2, 16))
        f.write(b"data")
        f.write(struct.pack("<I", len(frames)))
        f.write(frames)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", default="assets/sound/minecart")
    args = ap.parse_args()
    os.makedirs(args.dest, exist_ok=True)
    for v in (1, 2, 3):
        p = os.path.join(args.dest, "base%d.wav" % v)
        _write_wav(p, _synth(seed=1000 + v))
        print("wrote", p)


if __name__ == "__main__":
    main()
