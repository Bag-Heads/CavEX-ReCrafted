def _struct_bodies(text):
    """Yield (name, body) for every `struct block NAME = { ... };` in text,
    expanding same-file object-like macros used inside the body."""
    macros = {}
    for m in re.finditer(r"^#define\s+(\w+)\s+((?:.*\\\n)*.*)$", text, re.M):
        macros[m.group(1)] = m.group(2).replace("\\\n", " ")
    for m in re.finditer(r"struct\s+block\s+(\w+)\s*=\s*\{", text):
        depth, i = 1, m.end()
        while depth and i < len(text):
            c = text[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            i += 1
        body = text[m.end():i - 1]
        for name, val in macros.items():
            if re.search(r"\b%s\b" % re.escape(name), body):
                body = re.sub(r"\b%s\b" % re.escape(name), lambda _m: val, body)
        yield m.group(1), body


def _field(body, name):
    # Only top-level `.name =` (not `.block_item.name`, not inside nested braces
    # that start with another designator) -- the light fields are all top level.
    m = re.search(r"(?<![\w.])\.%s\s*=\s*([^,\n}]+)" % name, body)
    return m.group(1).strip() if m else None


def _strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def extract_light_table(repo_root):
    """Re-derive {id: (emission, opacity)} from source/block/*.c exactly the way
    server_world_beta_light_opacity() and the light engine read them."""
    block_dir = os.path.join(repo_root, "source", "block")
    structs = {}
    for fn in sorted(os.listdir(block_dir)):
        if not fn.endswith(".c"):
            continue
        with open(os.path.join(block_dir, fn), encoding="utf-8",
                  errors="replace") as f:
            text = _strip_comments(f.read())
        for name, body in _struct_bodies(text):
            lum = _field(body, "luminance")
            see = _field(body, "can_see_through")
            op = _field(body, "opacity")
            lum = int(lum, 0) if lum else 0
            see = see == "true"
            op = int(op, 0) if op else 0
            structs[name] = (lum & 15, (op & 15) if see else 255)
    with open(os.path.join(block_dir, "blocks.c"), encoding="utf-8") as f:
        reg = _strip_comments(f.read())
    table = {}
    for m in re.finditer(r"blocks\[(\d+)\]\s*=\s*&(\w+)\s*;", reg):
        bid, name = int(m.group(1)), m.group(2)
        if name not in structs:
            raise KeyError("blocks[%d] = &%s: struct not found" % (bid, name))
        table[bid] = structs[name]
    return table


def light_of(block_id, table=BAKED_LIGHT_TABLE):
    return table.get(block_id, (0, 0))


if __name__ == "__main__":
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    t = extract_light_table(root)
    if "--print" in sys.argv:
        items = ", ".join("%d: (%d, %d)" % (k, v[0], v[1]) for k, v in sorted(t.items()))
        print("BAKED_LIGHT_TABLE = {%s}" % items)
    diff = {k: (BAKED_LIGHT_TABLE.get(k), t.get(k))
            for k in set(t) | set(BAKED_LIGHT_TABLE)
            if BAKED_LIGHT_TABLE.get(k) != t.get(k)}
    print("drift:", diff if diff else "none")
    sys.exit(1 if diff else 0)
