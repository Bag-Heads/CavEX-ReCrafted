static void test_seed_expression(void) {
	// x*x*3121 + x*45238971 + z*z*418711 + z*13761, Java int32 wraparound.
	// (0,0): every term is 0.
	assert(precip_column_seed(0, 0) == 0);
	// (1,0): 1*1*3121 + 1*45238971 = 3121 + 45238971 = 45242092 (no overflow).
	assert(precip_column_seed(1, 0) == 45242092);
	// (0,1): 1*1*418711 + 1*13761 = 418711 + 13761 = 432472 (no overflow).
	assert(precip_column_seed(0, 1) == 432472);
	// (5,5): x*x*3121=78025; x*45238971=226194855; z*z*418711=10467775;
	// z*13761=68805. Sum = 78025+226194855+10467775+68805 = 236809460 (no
	// overflow: well under INT32_MAX).
	assert(precip_column_seed(5, 5) == 236809460);
	// (-5,-5): x*x*3121=78025 (squares are positive regardless of sign);
	// x*45238971 = -226194855; z*z*418711=10467775; z*13761=-68805.
	// Sum = 78025-226194855+10467775-68805 = -215717860.
	assert(precip_column_seed(-5, -5) == -215717860);
	// (100,-200): DELIBERATELY overflows int32 mid-expression -- hand-worked
	// via 32-bit two's-complement wraparound at EACH term:
	//   x*x*3121       = 100*100*3121 = 31210000                  (no overflow)
	//   x*45238971     = 4523897100 mod 2^32 = 228929804           (wraps, stays positive: < 2^31)
	//   z*z*418711     = 40000*418711 = 16748440000 mod 2^32 = 3863538112,
	//                    which is >= 2^31 so as signed int32 = 3863538112 - 2^32 = -431429184
	//   z*13761        = -200*13761 = -2752200                    (no overflow)
	//   sum (left-to-right, each add wraps too):
	//     31210000 + 228929804 = 260139804
	//     260139804 + (-431429184) = -171289380
	//     -171289380 + (-2752200) = -174041580
	assert(precip_column_seed(100, -200) == -174041580);
	// (-1000,1000) and (12,-3): cross-checked only against the independent
	// Python LCG oracle (values quoted, not re-derived by hand here) --
	// included to widen the swept spread the way RENDER_DISPATCH.md asks
	// ("a spread of (x,z) incl. negatives").
	assert(precip_column_seed(-1000, 1000) == -1350332048);
	assert(precip_column_seed(12, -3) == 547044192);
}

static void test_y_range_clamp_and_skip(void) {
	int32_t y0, y1;

	// Ordinary case: py=64, r=5, top=10 (well below the window) -> both
	// bounds come from the +-r window, unclamped by top.
	precip_column_y_range(10, 64, 5, &y0, &y1);
	assert(y0 == 59 && y1 == 69);

	// top ABOVE the whole [py-r, py+r] window (e.g. a cliff/mountain far
	// above the player) -> BOTH y0 and y1 clamp up to top and collapse to
	// the SAME value: the column must be skipped entirely (var24 == var25 ->
	// no draw, per the decompile). This is the y0==y1 skip rule.
	precip_column_y_range(100, 64, 5, &y0, &y1);
	assert(y0 == 100 && y1 == 100);
	assert(y0 == y1);

	// top exactly AT the lower window edge -> y0 clamps to top (== itself),
	// y1 unaffected (still above top) -> NOT equal, draws.
	precip_column_y_range(59, 64, 5, &y0, &y1);
	assert(y0 == 59 && y1 == 69);

	// top one above the lower edge -> y0 clamps up by one, still != y1.
	precip_column_y_range(60, 64, 5, &y0, &y1);
	assert(y0 == 60 && y1 == 69);

	// SNOW-only top<0 clamp (RAIN never applies this -- see
	// precip_snow_clamp_top's citation): top<0 -> 0; top>=0 unchanged.
	assert(precip_snow_clamp_top(-1) == 0);
	assert(precip_snow_clamp_top(-1000) == 0);
	assert(precip_snow_clamp_top(0) == 0);
	assert(precip_snow_clamp_top(5) == 5);

	// RAIN pass with a genuinely negative top (no clamp): py=5, r=5,
	// top=-1 -> y0=max(0,-1)=0, y1=max(10,-1)=10 (top never wins here since
	// it's below both window edges) -- included so a future accidental
	// clamp-everywhere regression on the RAIN path is caught.
	precip_column_y_range(-1, 5, 5, &y0, &y1);
	assert(y0 == 0 && y1 == 10);
}

