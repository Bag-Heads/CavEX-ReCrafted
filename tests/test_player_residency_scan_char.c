/* Characterization: host AND guest player material scans next to a chunk that
 * is NOT resident follow Beta 1.7.3 DEDICATED-SERVER semantics (Astra ruling S,
 * next-gaps-0924 L1; caller table tmp/jobs/next-gaps-0924/L1-callers.md).
 * Expected to PASS on aa3ce112: it pins current behaviour, it is not a RED.
 *
 * Beta server (mcb173-retromcp/minecraft_server/src_original/.../src):
 *  - The player's Entity.onUpdate (water/lava/fire/air) runs from the movement
 *    packet, NOT from the +-32 World.updateEntityWithOptionalForce gate:
 *    NetServerHandler.java:91,113,154 -> EntityPlayerMP.onUpdateEntity
 *    EntityPlayerMP.java:118-119 (super.onUpdate). The gated loaded-list pass
 *    only reaches the trivial EntityPlayerMP.onUpdate (EntityPlayerMP.java:
 *    66-77). World.java:1017-1021 is the gate ordinary entities get.
 *  - An unloaded cell reads as air: World.getBlockId (World.java:141-142) ->
 *    ChunkProviderServer.provideChunk returns dummyChunk unless a load
 *    override is set (ChunkProviderServer.java:84-86); EmptyChunk.getBlockID
 *    returns 0 (EmptyChunk.java:35-37). Nothing is loaded or generated.
 *  - Hence isMaterialInBB(lava) (World.java:1225-1245) has no chunk preflight:
 *    it sees lava in the resident cells and air in the missing ones, while
 *    isBoundingBoxBurning (World.java:1162-1170) and handleMaterialAcceleration
 *    (World.java:1185-1193) fail closed through their own checkChunksExist.
 *  - The update itself continues: fire cadence, air (eye-cell water), health.
 *
 * Geometry: only chunk (0,0) is resident. Positive edge: body at x=15.85
 * straddles into missing chunk (1,0). Negative edge: body at x=0.15 straddles
 * into missing chunk (-1,0) (floor of a negative coordinate). No chunk may be
 * loaded or generated by any of this: the resident count, the two missing
 * chunks, and the region-probe counter are all pinned. */
