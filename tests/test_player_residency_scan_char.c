void server_local_test_apply_guest_hazards(struct server_local*);

static struct server_local s;
static struct server_player guest;
static char fixture[128];
static volatile int draining = 1;
static int failures;
static int resident_before;
static uint32_t stats_before;

#define FEET_Y 70.0
#define CELL_Z 8

static void golden(const char* edge, const char* body, const char* what,
	int actual, int expected) {
	if(actual != expected) {
		fprintf(stderr, "FAIL %s %s %s: actual=%d expected=%d\n", edge, body,
			what, actual, expected);
		failures++;
	} else {
		printf("PASS %s %s %s: %d\n", edge, body, what, actual);
	}
}

static void* drain(void* unused) {
	(void)unused;
	while(draining) {
		clin_drain_discard();
		thread_msleep(1);
	}
	clin_drain_discard();
	return NULL;
}

static void put(int x, int y, int z, int block) {
	struct block_data expected = {.type = (uint8_t)block};
	if(server_world_set_block(&s.worlds[0], x, y, z, expected))
		return;
	struct block_data current;
	assert(server_world_get_block(&s.world, x, y, z, &current));
	assert(current.type == expected.type);
}

static int resident_chunks(void) {
	int resident = -1;
	server_world_perf_counters(&s.world, NULL, NULL, &resident);
	return resident;
}

/* The resident cell column the body overlaps: clear it to air. */
static void clear_cell(int x) {
	for(int y = 69; y <= 72; y++)
		put(x, y, CELL_Z, BLOCK_AIR);
}

static void reset_body(struct server_player* p, double x) {
	p->has_pos = true;
	p->finished_loading = true;
	p->x = x;
	p->y = FEET_Y + (double)PLAYER_EYE_HEIGHT;
	p->z = (double)CELL_Z + 0.5;
	p->health = MAX_PLAYER_HEALTH;
	p->hurt_resist_time = 0;
	p->last_damage = 0;
	p->damage_remainder = 0;
	p->oxygen = MAX_OXYGEN;
	p->fire = -PLAYER_FIRE_RESISTANCE;
	p->fall_distance = 0.0F;
	p->vel_x = p->vel_y = p->vel_z = 0.0F;
	p->old_vel_y = 0.0F;
	p->on_ground = true;
	p->spawn_x = (int)x;
	p->spawn_y = (int)FEET_Y;
	p->spawn_z = CELL_Z;
	p->active_inventory = &p->inventory;
}

/* Beta Entity.handleLavaMovement box, exactly as the host helper
 * server_local_player_body_in_lava_for builds it (server_local.c, static):
 * the float-sized 0.6x1.8 body inset 0.1/0.4/0.1 from the eye position. The
 * guest pass below calls that helper itself. */
static bool host_lava_scan(const struct server_player* p) {
	const double half_width = (double)(0.6F / 2.0F);
	const double feet_y = p->y - (double)PLAYER_EYE_HEIGHT;
	return server_world_aabb_has_lava(&s.world,
		p->x - half_width + (double)0.1F, feet_y + (double)0.4F,
		p->z - half_width + (double)0.1F, p->x + half_width - (double)0.1F,
		feet_y + (double)PLAYER_BODY_HEIGHT - (double)0.4F,
		p->z + half_width - (double)0.1F);
}

/* One player update for the chosen body.
 * Guest: the production guest pass (server_local_apply_guest_fire_and_cactus_
 * hazards: its own water/lava/fire/cactus scans, eye-cell air, fire cadence).
 * Host: the production host scans (body-water helper, fire/cactus contact
 * hook) composed into the production host hazard pass exactly as the
 * server_local_update tail does. The full host tick is NOT used here: its
 * near-ring STREAMING (the PlayerManager analogue) makes the neighbours
 * resident before the tail runs, which would hide the missing chunk -- that
 * is residency, not a scan-triggered load. The host hazard hook passes the
 * body-water flag as the head flag too, so host air is not asserted; the guest
 * pass pins eye-cell air. */
static void update(const char* edge, bool host, int want_lava) {
	if(host) {
		bool water = server_local_player_body_in_water_for(&s, &s.player);
		bool cactus = false, fire = false;
		server_local_test_player_block_contact(&s, &cactus, &fire);
		bool lava = host_lava_scan(&s.player);
		golden(edge, "host", "scan: body water", water, 0);
		golden(edge, "host", "scan: burning box", fire, 0);
		golden(edge, "host", "scan: cactus", cactus, 0);
		golden(edge, "host", "scan: lava", lava, want_lava);
		(void)server_local_test_apply_player_hazards(&s, water, lava, fire,
			cactus);
	} else {
		s.guest_gameplay = true;
		s.guest_actor = &guest;
		server_local_test_apply_guest_hazards(&s);
		s.guest_gameplay = false;
		s.guest_actor = NULL;
	}
}

static void assert_no_load(const char* edge, const char* body) {
	golden(edge, body, "resident chunk count", resident_chunks(),
		resident_before);
	golden(edge, body, "missing chunk (1,0) still missing",
		server_world_is_chunk_loaded(&s.world, 1, 0), 0);
	golden(edge, body, "missing chunk (-1,0) still missing",
		server_world_is_chunk_loaded(&s.world, -1, 0), 0);
	golden(edge, body, "region probes (no disk load)",
		(int)server_world_region_stat_count(), (int)stats_before);
}

/* edge: name; body_x: player X; cell_x: the RESIDENT cell the box overlaps. */
static void run_edge(const char* edge, double body_x, int cell_x, bool host) {
	const char* who = host ? "host" : "guest";
	struct server_player* p = host ? &s.player : &guest;
	if(!host)
		reset_body(&s.player, 8.5); /* host parked mid-chunk, dry */
	clear_cell(cell_x);

	/* 1. Lava in the resident cell: isMaterialInBB has NO chunk preflight, so
	 * it still sees the lava (4-point hit, 600-tick burn); the burning box that
	 * would add moveEntity's +1 fails closed on the missing chunk, so fire stays
	 * 600 (a fully resident box gives 601 -- test_lava_aabb_golden C). */
	reset_body(p, body_x);
	put(cell_x, 70, CELL_Z, BLOCK_LAVA_STILL);
	update(edge, host, 1);
	golden(edge, who, "lava resident-cell health", p->health,
		MAX_PLAYER_HEALTH - 4 * (HEALTH_PER_HEART / 2));
	golden(edge, who, "lava hit, burning box fail-closed: fire", p->fire, 600);
	clear_cell(cell_x);

	/* 2. No material in the resident cell: the missing cells read as air. */
	reset_body(p, body_x);
	update(edge, host, 0);
	golden(edge, who, "missing cells as air: health", p->health,
		MAX_PLAYER_HEALTH);
	golden(edge, who, "missing cells as air: fire", p->fire,
		-PLAYER_FIRE_RESISTANCE);

	/* 3. Fire in the resident cell: isBoundingBoxBurning's own
	 * checkChunksExist fails closed -- no contact hit, no ignition ramp. */
	reset_body(p, body_x);
	put(cell_x, 70, CELL_Z, BLOCK_FIRE);
	update(edge, host, 0);
	golden(edge, who, "fire box fail-closed: health", p->health,
		MAX_PLAYER_HEALTH);
	golden(edge, who, "fire box fail-closed: fire", p->fire,
		-PLAYER_FIRE_RESISTANCE);
	clear_cell(cell_x);

	/* 4. Water in the resident cells (body + eye): handleMaterialAcceleration
	 * fails closed, so a burning body is NOT quenched and its fire cadence
	 * continues (fire 100 -> 1-point tick -> 99), while the eye-cell air
	 * sample still drains oxygen: the update itself runs. */
	reset_body(p, body_x);
	p->fire = 100;
	put(cell_x, 70, CELL_Z, BLOCK_WATER_STILL);
	put(cell_x, 71, CELL_Z, BLOCK_WATER_STILL);
	update(edge, host, 0);
	golden(edge, who, "water box fail-closed: fire keeps burning", p->fire,
		99);
	golden(edge, who, "water box fail-closed: burn tick health", p->health,
		MAX_PLAYER_HEALTH - HEALTH_PER_HEART / 2);
	if(!host)
		golden(edge, who, "eye-cell air advances", p->oxygen, MAX_OXYGEN - 1);
	clear_cell(cell_x);

	assert_no_load(edge, who);
}

int main(void) {
	test_fixture_dir("test_player_residency_scan_char_tmp", fixture,
		sizeof fixture);
	assert(clin_init());
	assert(svin_init());
	struct thread worker;
	assert(thread_create(&worker, drain, NULL, 64));
	blocks_init();
	MKDIR(fixture);
	MKDIR(test_fixture_join(fixture, "/region"));
	string_t level;
	string_init_set_str(level, fixture);
	memset(&s, 0, sizeof s);
	memset(&guest, 0, sizeof guest);
	dict_entity_init(s.entities);
	server_world_create(&s.world, level, WORLD_DIM_OVERWORLD, 4242, true);
	s.worlds[0].session = &s; /* A1a (D1): the owning session (callbacks, services); not the archive binding `local` */
	s.scheduled_tick_budget = 0;
	rand_gen_seed(&s.rand_src);
	struct server_chunk* chunk = NULL;
	assert(server_world_load_chunk(&s.world, 0, 0, &chunk) && chunk);
	assert(inventory_create(&s.player.inventory, &inventory_logic_player, &s,
		&s.player, INVENTORY_SIZE, 0, 0, 0));
	assert(inventory_create(&guest.inventory, &inventory_logic_player, &s,
		&guest, INVENTORY_SIZE, 0, 0, 0));
	s.weather.rain_strength = s.weather.prev_rain_strength = 0.0F;
	s.zombie_demo = false;
	reset_body(&s.player, 8.5);
	reset_body(&guest, 8.5);

	assert(!server_world_is_chunk_loaded(&s.world, 1, 0));
	assert(!server_world_is_chunk_loaded(&s.world, -1, 0));
	resident_before = resident_chunks();
	stats_before = server_world_region_stat_count();

	run_edge("+X edge (missing 1,0)", 15.85, 15, true);
	run_edge("-X edge (missing -1,0)", 0.15, 0, true);
	run_edge("+X edge (missing 1,0)", 15.85, 15, false);
	run_edge("-X edge (missing -1,0)", 0.15, 0, false);

	draining = 0;
	thread_join(&worker);
	string_clear(level);
	test_fixture_dir_cleanup(fixture);
	if(failures != 0) {
		fprintf(stderr, "test_player_residency_scan_char: FAIL (%d)\n",
			failures);
		return 1;
	}
	puts("test_player_residency_scan_char: PASS");
	return 0;
}
