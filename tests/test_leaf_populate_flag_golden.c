/*
	Golden: populate-time leaf flagging when a tree's trunk overwrites its own
	canopy (source/worldgen/populate.c wgen_leaves_on_removal, called by the
	writer after a non-leaf id replaces a LEAVES byte -- this fixture's fw_set
	mirrors the live quad_set in server_world.c).

	Beta 1.7.3 (decompile 740c583), derived by hand -- never from CaveWii:
	  WorldGenTrees.generate: height h = nextInt(3)+4 [:12]; the canopy loop
	    [:46-59] writes leaves on layers y0+h-3 .. y0+h for every
	    non-opaque cell of the layer's square, INCLUDING the trunk column
	    (centre passes the corner-skip test); then the trunk loop [:62-66]
	    turns each of the h trunk cells that is air or leaves into wood, and
	    overwrites the three canopy cells y0+h-3 .. y0+h-1 on the column.
	  WorldGenForest (birch): identical shape, h = nextInt(3)+5 [:7], leaves
	    and wood via setBlockAndMetadata(.., 2) [:56, :65].
	  World.setBlock / setBlockAndMetadata -> Chunk.setBlockID [Chunk.java:
	    277-286] / setBlockIDWithMetadata [:240-248]: the OLD block's
	    onBlockRemoval fires whenever the id changes (18 -> 17 here).
	  BlockLeaves.onBlockRemoval [BlockLeaves.java:33-50]: gate
	    checkChunksExist(radius 2), then every leaf in the 3x3x3 around the
	    replaced cell gets metadata | 8. The cell itself already reads as wood.
	  => For an isolated simple tree with trunk base (tx,y0,tz) and height H,
	     the flagged leaves are EXACTLY those with |dx| <= 1, |dz| <= 1 and
	     y0+H-4 <= y <= y0+H (the union of the three 3x3x3 boxes clipped to
	     where leaves exist: the top canopy cell y0+H on the column is a leaf
	     within 1 of trunk cell y0+H-1; no leaf lies below y0+H-3 for an
	     isolated tree). Every other leaf keeps bit 8 clear.
	  Chunk gate: trees root at col+8..+23 [WorldGenTrees caller:
	    BiomeDecorator/ChunkProviderGenerate x = k*16 + nextInt(16) + 8], so
	    the radius-2 box (6..25) always lies inside the 2x2 populate window
	    that ChunkProviderLoadOrGenerate.loadChunk:76-90 guarantees -> the
	    gate always passes for the trunk overwrite; deterministic.

	Oracle note: mc173 cannot check this -- its BlockLeaves removal arm is
	empty, and CaveWii's oracle dump (tests/oracle/dump_chunk.c) captures
	terrain only (no populate), so test_oracle_worldgen is unaffected either
	way. This golden pins the rule from the decompile instead.

	Big trees (branches = off-column logs) and trees whose canopies touch are
	excluded by an isolation filter (no other log within horizontal Chebyshev
	distance 6 of the trunk); the trial asserts enough isolated trees were
	actually checked. Trees are generated by the production worldgen_trees on
	a flat world wrapped by the production populate wrapper (the same wrapper
	worldgen_populate applies to the live quad writer).
*/

#include <assert.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "block/blocks_data.h"
#include "worldgen/biome.h"
#include "worldgen/java_random.h"
#include "worldgen/populate.h"
#include "worldgen/tree.h"

#define FW_W 48
#define FW_SURFACE 64
struct flatworld {
	uint8_t ids[FW_W * FW_W * 128];
	uint8_t meta[FW_W * FW_W * 128];
};

static int fw_index(int x, int y, int z, int* idx) {
	if(y < 0 || y >= 128 || x < 0 || x >= FW_W || z < 0 || z >= FW_W)
		return 0;
	*idx = (x * FW_W + z) * 128 + y;
	return 1;
}
static uint8_t fw_get(void* ctx, int x, int y, int z) {
	struct flatworld* f = ctx;
	int idx;
	return fw_index(x, y, z, &idx) ? f->ids[idx] : BLOCK_AIR;
}
static uint8_t fw_get_meta(void* ctx, int x, int y, int z) {
	struct flatworld* f = ctx;
	int idx;
	return fw_index(x, y, z, &idx) ? f->meta[idx] : 0;
}
static struct wgen_world* g_view; /* the fixture's own view, for the pass */
static void fw_set(void* ctx, int x, int y, int z, uint8_t id, uint8_t meta) {
	struct flatworld* f = ctx;
	int idx;
	if(fw_index(x, y, z, &idx)) {
		uint8_t old = f->ids[idx];
		f->ids[idx] = id;
		f->meta[idx] = meta;
		if(old == BLOCK_LEAVES && id != BLOCK_LEAVES)
			wgen_leaves_on_removal(g_view, 0, 0, x, y, z);
	}
}
static int fw_height(void* ctx, int x, int z) {
	struct flatworld* f = ctx;
	if(x < 0 || x >= FW_W || z < 0 || z >= FW_W)
		return FW_SURFACE + 1;
	for(int y = 127; y >= 0; y--) {
		uint8_t b = f->ids[(x * FW_W + z) * 128 + y];
		if(b == BLOCK_GRASS || b == BLOCK_DIRT || b == BLOCK_STONE)
			return y + 1;
	}
	return 0;
}
static void fw_fill(struct flatworld* f) {
	for(int x = 0; x < FW_W; x++)
		for(int z = 0; z < FW_W; z++)
			for(int y = 0; y < 128; y++) {
				uint8_t b = BLOCK_AIR;
				if(y < FW_SURFACE)
					b = (y == FW_SURFACE - 1) ? BLOCK_DIRT : BLOCK_STONE;
				else if(y == FW_SURFACE)
					b = BLOCK_GRASS;
				f->ids[(x * FW_W + z) * 128 + y] = b;
			}
	memset(f->meta, 0, sizeof(f->meta));
}

static int id_at(struct flatworld* f, int x, int y, int z) {
	return fw_get(f, x, y, z);
}
static int meta_at(struct flatworld* f, int x, int y, int z) {
	return fw_get_meta(f, x, y, z);
}

/* An isolated simple tree rooted at (tx, y0, tz): a vertical log run on dirt
 * with no other log within horizontal Chebyshev 6. Returns its height or 0. */
static int simple_tree_height(struct flatworld* f, int tx, int tz, int* y0_out) {
	int y0 = FW_SURFACE + 1;
	if(id_at(f, tx, y0, tz) != BLOCK_LOG || id_at(f, tx, y0 - 1, tz) != BLOCK_DIRT)
		return 0;
	int h = 0;
	while(id_at(f, tx, y0 + h, tz) == BLOCK_LOG)
		h++;
	for(int x = tx - 6; x <= tx + 6; x++)
		for(int z = tz - 6; z <= tz + 6; z++) {
			if(x == tx && z == tz)
				continue;
			for(int y = FW_SURFACE; y < FW_SURFACE + 24; y++)
				if(id_at(f, x, y, z) == BLOCK_LOG)
					return 0; /* a branch (big tree) or a neighbour: skip */
		}
	*y0_out = y0;
	return h;
}

int main(void) {
	struct flatworld* f = malloc(sizeof *f);
	assert(f);
	struct java_random r;
	int checked_trees = 0, flagged_leaves = 0, clear_leaves = 0;
	const int64_t seeds[] = {42, 1337, 20260924, -7, 987654321, 31337, 4242, 99};
	const enum biome biomes[] = {BIOME_FOREST, BIOME_PLAINS, BIOME_SEASONAL_FOREST};
	for(size_t bi = 0; bi < sizeof biomes / sizeof biomes[0]; bi++)
		for(size_t si = 0; si < sizeof seeds / sizeof seeds[0]; si++) {
			fw_fill(f);
			struct wgen_world w = {
				.ctx = f, .get = fw_get, .set = fw_set, .height = fw_height,
				.get_meta = fw_get_meta,
			};
			g_view = &w;
			jrand_set_seed(&r, seeds[si]);
			worldgen_trees(&w, &r, biomes[bi], 2.0, 0, 0);

			for(int tx = 6; tx <= 25; tx++)
				for(int tz = 6; tz <= 25; tz++) {
					int y0;
					int h = simple_tree_height(f, tx, tz, &y0);
					if(h < 4 || h > 7)
						continue;
					checked_trees++;
					/* every leaf around the tree: flagged iff in the rule box */
					for(int x = tx - 4; x <= tx + 4; x++)
						for(int z = tz - 4; z <= tz + 4; z++)
							for(int y = y0 - 1; y <= y0 + h + 2; y++) {
								if(id_at(f, x, y, z) != BLOCK_LEAVES)
									continue;
								bool expect = abs(x - tx) <= 1 && abs(z - tz) <= 1
									&& y >= y0 + h - 4 && y <= y0 + h;
								int m = meta_at(f, x, y, z);
								if(((m & 8) != 0) != expect) {
									printf("FAIL seed %lld biome %d tree (%d,%d,%d) h=%d: leaf (%d,%d,%d) meta %d, expected bit8=%d\n",
										   (long long)seeds[si], (int)biomes[bi], tx, y0, tz, h, x, y, z, m, (int)expect);
									assert(0 && "populate-time leaf flag rule");
								}
								if(expect) {
									assert((m & 3) == (meta_at(f, tx, y0, tz) & 3)
										   && "species bits preserved under the flag");
									flagged_leaves++;
								} else
									clear_leaves++;
							}
					/* the trunk column itself carries no flag (it is wood) */
					for(int y = y0; y < y0 + h; y++)
						assert((meta_at(f, tx, y, tz) & 8) == 0);
				}
		}
	printf("test_leaf_populate_flag_golden: %d isolated trees, %d flagged leaves (3x3 column, top 5 layers), %d clear leaves\n",
		   checked_trees, flagged_leaves, clear_leaves);
	assert(checked_trees >= 12 && flagged_leaves >= 12 * 10 && clear_leaves > flagged_leaves);

	/* the gate: a removal whose radius-2 box leaves the 2x2 window flags nothing */
	{
		fw_fill(f);
		struct wgen_world w = {
			.ctx = f, .get = fw_get, .set = fw_set, .height = fw_height,
			.get_meta = fw_get_meta,
		};
		g_view = &w;
		/* leaf at x=1: box x-2 = -1 -> chunk -1 does not exist -> no flag */
		w.set(w.ctx, 1, 70, 10, BLOCK_LEAVES, 0);
		w.set(w.ctx, 2, 70, 10, BLOCK_LEAVES, 1);
		w.set(w.ctx, 1, 70, 10, BLOCK_LOG, 0);
		assert(meta_at(f, 2, 70, 10) == 1 && "gate failed -> untouched");
		/* leaf at x=2: box 0..4 -> chunk 0 only -> flags */
		w.set(w.ctx, 2, 70, 10, BLOCK_LOG, 0);
		assert(id_at(f, 2, 70, 10) == BLOCK_LOG); /* no leaf neighbours left */
		w.set(w.ctx, 3, 70, 10, BLOCK_LEAVES, 2);
		w.set(w.ctx, 2, 71, 10, BLOCK_LEAVES, 0);
		w.set(w.ctx, 2, 71, 10, BLOCK_STONE, 0); /* stone replaces a leaf: fires too */
		assert(meta_at(f, 3, 70, 10) == (2 | 8) && "any id replacing a leaf flags r1");
		/* same-id write never fires here (unreachable in Beta anyway: no
		 * generator writes a leaf over a leaf, opaqueCubeLookup[18] is true --
		 * Block.java:151; see populate.h) */
		w.set(w.ctx, 3, 71, 10, BLOCK_LEAVES, 0);
		w.set(w.ctx, 3, 72, 10, BLOCK_LEAVES, 0);
		w.set(w.ctx, 3, 72, 10, BLOCK_LEAVES, 1);
		assert(meta_at(f, 3, 71, 10) == 0 && "leaves over leaves: no removal");
		printf("  gate + any-id + same-id cases OK\n");
	}
	free(f);
	return 0;
}
