// ---- helpers -----------------------------------------------------------

static void stub_put(size_t slot, char c) {
	assert(slot < STUB_CAP);
	stub_items[slot].id = 1;
	stub_items[slot].durability = 0;
	stub_items[slot].count = (uint8_t)c;
	stub_occupied[slot] = true;
}

static char stub_get(size_t slot) {
	assert(slot < STUB_CAP && stub_occupied[slot]);
	return (char)stub_items[slot].count;
}

// True iff `changes` contains exactly one entry and it equals `slot`.
// Uses M*LIB iteration (always generated by DICT_SET_DEF) rather than _get,
// so the assertion does not depend on the optional accessor name.
static bool changes_is_only(set_inv_slot_t changes, size_t slot) {
	if(set_inv_slot_size(changes) != 1)
		return false;
	set_inv_slot_it_t it;
	for(set_inv_slot_it(it, changes); !set_inv_slot_end_p(it);
		set_inv_slot_next(it)) {
		if(*set_inv_slot_ref(it) == slot)
			return true;
	}
	return false;
}

int main(void) {
	struct inventory dummy = {0};

	// (1) increment ' ' (0x20) -> '!' (0x21)
	{
		set_inv_slot_t changes;
		set_inv_slot_init(changes);
		stub_put(3, ' ');

		bool moved = inventory_logic_sign.pre_action(&dummy, NULL, 3, true, changes);

		assert(!moved);                  // chars never move as items
		assert(stub_get(3) == '!');      // 0x20 -> 0x21
		assert(changes_is_only(changes, 3));   // touched slot pushed once
		set_inv_slot_clear(changes);
	}

	// (2) increment '~' (0x7E) wraps to ' '
	{
		set_inv_slot_t changes;
		set_inv_slot_init(changes);
		stub_put(7, '~');

		bool moved = inventory_logic_sign.pre_action(&dummy, NULL, 7, true, changes);

		assert(!moved);
		assert(stub_get(7) == ' ');      // 0x7E -> 0x7F -> wrap to 0x20
		assert(changes_is_only(changes, 7));
		set_inv_slot_clear(changes);
	}

	// (3) decrement ' ' wraps to '~'
	{
		set_inv_slot_t changes;
		set_inv_slot_init(changes);
		stub_put(11, ' ');

		bool moved = inventory_logic_sign.pre_action(&dummy, NULL, 11, false, changes);

		assert(!moved);
		assert(stub_get(11) == '~');     // 0x20 -> 0x1F -> wrap to 0x7E
		assert(changes_is_only(changes, 11));
		set_inv_slot_clear(changes);
	}

	// (4) empty slot: nothing happens, nothing pushed, still returns false
	{
		set_inv_slot_t changes;
		set_inv_slot_init(changes);

		bool moved = inventory_logic_sign.pre_action(&dummy, NULL, 42, true, changes);

		assert(!moved);
		assert(set_inv_slot_size(changes) == 0);
		set_inv_slot_clear(changes);
	}

	// (5) [maintainer ruling 2026-08-17] column 15 of every line (slot %
	// SIGN_LINE_COLS == SIGN_BETA_MAX_CHARS) is past Beta's 15-char gate
	// [740c583 GuiEditSign.keyTyped: `signText[line].length() < 15`] and the
	// char-cycle must not be a second door around the OSK/SRPC_SIGN_SET
	// clamp on inventory_sign_set_char -- it is a pinned no-op regardless of
	// direction, even on an occupied, seeded slot (proving the column itself
	// is frozen, not merely that ' ' happens to be a no-op input).
	{
		set_inv_slot_t changes;
		set_inv_slot_init(changes);
		stub_put(15, ' ');

		bool moved = inventory_logic_sign.pre_action(&dummy, NULL, 15, true, changes);

		assert(!moved);
		assert(stub_get(15) == ' ');            // unchanged: no wrap to '!'
		assert(set_inv_slot_size(changes) == 0); // nothing pushed
		set_inv_slot_clear(changes);
	}

	// (6) same gate, decrement direction, a different line's 16th cell.
	{
		set_inv_slot_t changes;
		set_inv_slot_init(changes);
		stub_put(63, ' ');

		bool moved = inventory_logic_sign.pre_action(&dummy, NULL, 63, false, changes);

		assert(!moved);
		assert(stub_get(63) == ' ');            // unchanged: no wrap to '~'
		assert(set_inv_slot_size(changes) == 0);
		set_inv_slot_clear(changes);
	}

	return 0;
}
