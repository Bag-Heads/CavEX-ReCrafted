// ---- stub inventory backing store --------------------------------------

#define STUB_CAP SIGN_SIZE

static struct item_data stub_items[STUB_CAP];
static bool stub_occupied[STUB_CAP];

bool inventory_get_slot(struct inventory* inv, size_t slot,
						struct item_data* item) {
	(void)inv;
	if(slot >= STUB_CAP || !stub_occupied[slot])
		return false;
	if(item)
		*item = stub_items[slot];
	return true;
}

void inventory_set_slot(struct inventory* inv, size_t slot,
						struct item_data item) {
	(void)inv;
	assert(slot < STUB_CAP);
	stub_items[slot] = item;
	stub_occupied[slot] = true;
}

