// Pins the sign char-cycle constants driven by inventory_logic_sign.pre_action.
// The IR-pointer poll added to screen_sign.c makes selected_slot reachable from
// the pointer (Wii adaptation), so the per-character increment/decrement math
// behind it is now user-reachable; this test locks that math byte-for-byte.
//
// pre_action is exercised on a stub inventory so we do not pull in the full
// inventory.c / items.c / server_local.c graph. Only inventory_sign.c is linked;
// every external symbol it references is stubbed below.

#include <assert.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "../source/item/inventory.h"
#include "../source/network/inventory_logic.h"

